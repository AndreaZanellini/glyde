//! The licenses of the code compiled into Glyde (MIT, BSD, Apache-2.0, OFL,
//! MPL-2.0, …) ask that their copyright and license text travel with every
//! copy of the binary. `THIRD-PARTY-LICENSES.txt` carries them; it is
//! generated by `packaging/third-party/generate.sh` and committed. These
//! tests keep it true: it lists exactly the crates the app is built from on
//! the three shipped platforms, and its accepted licenses are the ones
//! `deny.toml` allows.

use std::collections::BTreeSet;
use std::path::PathBuf;
use std::process::Command;

/// The platforms Glyde ships on (docs/SPEC.md §7).
const TARGETS: [&str; 3] = [
    "aarch64-apple-darwin",
    "x86_64-pc-windows-msvc",
    "x86_64-unknown-linux-gnu",
];

const REGENERATE: &str = "run packaging/third-party/generate.sh (needs: cargo install cargo-about \
     --locked --version 0.9.3 --features cli) and commit THIRD-PARTY-LICENSES.txt";

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn repo_file(relative: &str) -> String {
    let path = repo_root().join(relative);
    std::fs::read_to_string(&path)
        .unwrap_or_else(|err| panic!("read {}: {err}", path.display()))
        .replace("\r\n", "\n")
}

/// `name version` of every crate the `glyde` binary is compiled from on the
/// shipped platforms, as `cargo tree` resolves them for `-p glyde-app`: the
/// same dependencies and features as the release build. Build scripts' and
/// tests' dependencies are not in the binary; Glyde's own crates (path
/// dependencies) are covered by LICENSE and NOTICE.
fn shipped_crates() -> BTreeSet<String> {
    let mut cargo = Command::new(env!("CARGO"));
    cargo.current_dir(repo_root()).args([
        "tree",
        "--locked",
        "-p",
        "glyde-app",
        "-e",
        "normal",
        "--prefix",
        "none",
        "--format",
        "{p}",
    ]);
    for target in TARGETS {
        cargo.args(["--target", target]);
    }
    let output = cargo.output().expect("cargo tree runs");
    assert!(
        output.status.success(),
        "cargo tree failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let tree = String::from_utf8(output.stdout).expect("cargo tree prints UTF-8");
    tree.lines()
        // `name vX.Y.Z`, then ` (proc-macro)`, ` (/path)` for Glyde's own
        // crates, or ` (*)` for a repeat.
        .filter(|line| !line.contains(" (/") && !line.contains(":\\"))
        .filter_map(|line| {
            let mut words = line.split_whitespace();
            let name = words.next()?;
            let version = words.next()?.strip_prefix('v')?;
            Some(format!("{name} {version}"))
        })
        .collect()
}

/// `name version` of every package in Cargo.lock.
fn locked_crates() -> BTreeSet<String> {
    let lock = repo_file("Cargo.lock");
    let mut crates = BTreeSet::new();
    let mut name = None;
    for line in lock.lines() {
        if let Some(value) = line.strip_prefix("name = ") {
            name = Some(value.trim_matches('"').to_string());
        } else if let Some(value) = line.strip_prefix("version = ") {
            if let Some(name) = name.take() {
                crates.insert(format!("{name} {}", value.trim_matches('"')));
            }
        }
    }
    crates
}

/// `name version` of every crate the notices list (`  - name version …`).
fn listed_crates(notices: &str) -> BTreeSet<String> {
    notices
        .lines()
        .filter_map(|line| line.strip_prefix("  - "))
        .filter_map(|entry| {
            let mut words = entry.split_whitespace();
            let name = words.next()?;
            let version = words.next()?;
            // The fonts' entries carry a URL, not a crate version.
            version
                .starts_with(|c: char| c.is_ascii_digit())
                .then(|| format!("{name} {version}"))
        })
        .filter(|entry| !entry.starts_with("Inter ") && !entry.starts_with("JetBrains "))
        .collect()
}

/// Every crate in the binary has its license in the notices. cargo-about
/// filters platforms more coarsely than cargo (it keeps, for example, the
/// `windows-gnu` variants next to the `msvc` ones Glyde builds with), so the
/// notices may list a few more crates than the binary holds: harmless. But
/// each of them must still be in Cargo.lock, so an old version left behind
/// after an update also asks for a regeneration.
#[test]
fn the_third_party_notices_list_every_crate_in_the_app() {
    let shipped = shipped_crates();
    assert!(
        shipped.len() > 100 && shipped.iter().any(|c| c.starts_with("eframe ")),
        "cargo tree found the GUI tree ({} crates)",
        shipped.len()
    );
    let listed = listed_crates(&repo_file("THIRD-PARTY-LICENSES.txt"));
    let missing: Vec<_> = shipped.difference(&listed).collect();
    let locked = locked_crates();
    let stale: Vec<_> = listed.difference(&locked).collect();
    assert!(
        missing.is_empty() && stale.is_empty(),
        "THIRD-PARTY-LICENSES.txt is out of date with Cargo.lock: \
         missing {missing:?}, no longer in Cargo.lock {stale:?}; {REGENERATE}"
    );
}

#[test]
fn the_notices_carry_the_embedded_fonts_and_point_to_glydes_own_license() {
    let notices = repo_file("THIRD-PARTY-LICENSES.txt");
    for required in [
        "see LICENSE and\nNOTICE",
        "https://crates.io/crates/<name>/<version>",
        "  - Inter 4.1 (https://github.com/rsms/inter)",
        "  - JetBrains Mono 2.304 (https://github.com/JetBrains/JetBrainsMono)",
        "Copyright (c) 2016 The Inter Project Authors",
        "Copyright 2020 The JetBrains Mono Project Authors",
        "SIL OPEN FONT LICENSE Version 1.1",
        // egui's own fonts, through the epaint_default_fonts crate.
        "Ubuntu Font Licence",
        // MPL-2.0 asks that recipients be told where the source is.
        "Mozilla Public License 2.0 (MPL-2.0)",
    ] {
        assert!(notices.contains(required), "notices lack {required:?}");
    }
}

/// The license list of `[licenses] allow` in deny.toml, or of `accepted` in
/// about.toml: the quoted SPDX ids between the key's `[` and its `]`.
fn spdx_list(toml: &str, key: &str) -> BTreeSet<String> {
    let start = toml
        .find(&format!("\n{key} = ["))
        .unwrap_or_else(|| panic!("no `{key} = [` list"));
    let body = &toml[start..];
    let body = &body[..body.find("\n]").expect("list ends with `]`")];
    body.lines()
        .skip(1)
        .map(|line| line.split('#').next().unwrap_or("").trim())
        .filter_map(|line| line.strip_prefix('"'))
        .filter_map(|line| line.split('"').next())
        .map(str::to_string)
        .collect()
}

/// cargo deny decides which licenses a dependency may have; cargo-about must
/// accept exactly those, or the generator fails on a crate CI let in (or
/// lists one under a license CI would refuse).
#[test]
fn the_notices_accept_exactly_the_licenses_cargo_deny_allows() {
    let allowed = spdx_list(&repo_file("deny.toml"), "allow");
    let accepted = spdx_list(&repo_file("packaging/third-party/about.toml"), "accepted");
    assert!(allowed.contains("MIT") && allowed.contains("OFL-1.1"));
    assert_eq!(accepted, allowed);
}
